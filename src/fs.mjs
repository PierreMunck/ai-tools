import { existsSync, lstatSync, mkdirSync, readFileSync, readlinkSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import path from 'node:path'

export function readJson(file, fallback) {
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback
}

export function readText(file) {
  return existsSync(file) ? readFileSync(file, 'utf8') : ''
}

export function writeJson(file, data) {
  writeText(file, `${JSON.stringify(data, null, 2)}\n`)
}

export function writeText(file, text) {
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, text)
}

// Relative symlink so a project-scope install survives the repo being moved.
// Never overwrites something that is not ours: returns 'linked' | 'kept' | 'skipped'.
export function link(linkPath, target) {
  mkdirSync(path.dirname(linkPath), { recursive: true })
  let existing
  try {
    existing = lstatSync(linkPath)
  } catch {}
  if (existing) {
    const same =
      existing.isSymbolicLink() &&
      path.resolve(path.dirname(linkPath), readlinkSync(linkPath)) === path.resolve(target)
    return same ? 'kept' : 'skipped'
  }
  const type = statSync(target).isDirectory() ? 'dir' : 'file'
  symlinkSync(path.relative(path.dirname(linkPath), target), linkPath, type)
  return 'linked'
}

// Links a batch and reports it as one line, with a warning per path left alone.
export function linkAll(report, host, kind, dir, entries) {
  const counts = { linked: 0, kept: 0, skipped: 0 }
  for (const [name, target] of entries) {
    const outcome = link(path.join(dir, name), target)
    counts[outcome] += 1
    if (outcome === 'skipped') report.warn(host, `${path.join(dir, name)} exists and is not ours — left alone`)
  }
  const summary = Object.entries(counts)
    .filter(([, n]) => n)
    .map(([k, n]) => `${n} ${k}`)
    .join(', ')
  if (entries.length) report.ok(host, `${kind}: ${summary} → ${dir}`)
}

// Generated files carry a header so a later run can overwrite them, and a file
// someone wrote by hand under the same name is left alone.
export const GENERATED = '# generated by ai-tools — edit the source in the toolbox, then run `ai-tools install` again\n'

export function writeGenerated(report, host, file, body) {
  const current = readText(file)
  if (current && !current.startsWith(GENERATED)) {
    report.warn(host, `${file} exists and is not ours — left alone`)
    return false
  }
  writeText(file, GENERATED + body)
  return true
}
